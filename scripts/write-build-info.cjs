const fs = require("fs");
const path = require("path");
const cp = require("child_process");

const root = path.resolve(__dirname, "..");

const pkg = JSON.parse(
    fs.readFileSync(path.join(root, "package.json"), "utf8")
);

let commit = "dev";

try {
    commit = cp
        .execSync("git rev-parse --short=8 HEAD", { cwd: root })
        .toString()
        .trim();
} catch {
    commit = "dev";
}

const content = `// This file is auto-generated by scripts/write-build-info.cjs
export const APP_VERSION = ${JSON.stringify(pkg.version || "0.0.0")};
export const GIT_COMMIT = ${JSON.stringify(commit)};
`;

fs.writeFileSync(path.join(root, "src", "buildInfo.ts"), content);
console.log(`buildInfo.ts generated: ${pkg.version} [${commit}]`);
